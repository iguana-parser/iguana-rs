use std::{fs, io::Write, path::Path, time::Instant};

use proc_macro2::TokenStream;

use crate::{
    generator::{
        id::{EndSlot, NonterminalIds, SlotIds, TerminalIds},
        parser_gen::ParserGen,
    },
    grammar::{def::Grammar, slot::Slot},
};

pub struct GenConfig {
    pub ll1_optimization: bool,
}

impl Default for GenConfig {
    fn default() -> Self {
        Self {
            ll1_optimization: true,
        }
    }
}

pub struct GenerateResult {
    pub total_duration_ms: u64,
}

mod cargo_toml_gen;
mod id;
mod lib_gen;
mod main_gen;
mod parse_tree_gen;
mod parser_gen;
mod scanner_gen;
mod types_gen;
pub(crate) mod utils;

const GENERATED_HEADER_RUST: &str = "// @generated by iguana. Do not edit manually.\n";
const GENERATED_HEADER_TOML: &str = "# @generated by iguana. Do not edit manually.\n";

pub fn generate(
    grammar: &Grammar,
    output_dir: &Path,
    config: GenConfig,
) -> std::io::Result<GenerateResult> {
    let start = Instant::now();
    let mut nonterminal_ids = NonterminalIds::new(grammar.nonterminals().cloned());
    // TODO: also do the same for terminal ids to pass things via constructor
    let mut terminal_ids = TerminalIds::default();
    for terminal in grammar.terminals() {
        terminal_ids.insert(terminal.clone());
    }
    let mut slot_ids = SlotIds::new(grammar);
    for nonterminal in grammar.nonterminals() {
        let alternatives = grammar.alternatives(nonterminal);
        for (index, alternative) in alternatives.iter().enumerate() {
            for pos in 0..alternative.symbols.len() {
                let slot = Slot::new(nonterminal, alternative, pos);
                slot_ids.insert(slot);
            }
            let last_symbol_index = alternative.symbols.len();
            let end_slot = Slot::new(nonterminal, alternative, last_symbol_index);
            let end_slot_id = slot_ids.insert(end_slot);
            let nonterminal_id = nonterminal_ids.get_id(nonterminal);
            let end_slot = EndSlot {
                index,
                slot_id: end_slot_id,
            };
            nonterminal_ids.add_end_slot(nonterminal_id, end_slot);
        }
    }

    if !output_dir.exists() {
        fs::create_dir_all(output_dir)?;
    }

    write_toml_file(
        cargo_toml_gen::generate(grammar),
        &output_dir.join("Cargo.toml"),
    )?;

    let src_dir = output_dir.join("src");
    if !src_dir.exists() {
        fs::create_dir(&src_dir)?;
    }

    write_rust_file(
        to_string(lib_gen::generate(grammar)),
        &src_dir.join("lib.rs"),
    )?;
    let mut parser_gen =
        ParserGen::new(grammar, &nonterminal_ids, &terminal_ids, &slot_ids, config);
    let parser_code = parser_gen.generate();
    let grammar_comment = grammar
        .to_string()
        .lines()
        .map(|l| format!("// {l}"))
        .collect::<Vec<_>>()
        .join("\n");
    let parser_source = format!("{grammar_comment}\n{}", to_string(parser_code));
    write_rust_file(parser_source, &src_dir.join("parser.rs"))?;

    let scanner_code = scanner_gen::generate(grammar, &terminal_ids);
    write_rust_file(to_string(scanner_code), &src_dir.join("scanner.rs"))?;

    let parse_tree_code =
        parse_tree_gen::generate(grammar, &nonterminal_ids, &terminal_ids, &slot_ids);
    write_rust_file(to_string(parse_tree_code), &src_dir.join("parse_tree.rs"))?;

    let types_code = types_gen::generate();
    write_rust_file(to_string(types_code), &src_dir.join("types.rs"))?;

    let main_code = main_gen::generate(grammar);
    write_rust_file(to_string(main_code), &src_dir.join("main.rs"))?;

    Ok(GenerateResult {
        total_duration_ms: start.elapsed().as_millis() as u64,
    })
}

fn write_rust_file(content: impl AsRef<str>, path: &Path) -> std::io::Result<()> {
    let mut file = fs::File::create(path)?;
    file.write_all(GENERATED_HEADER_RUST.as_bytes())?;
    file.write_all(content.as_ref().as_bytes())?;
    file.write_all(b"\n")?;
    Ok(())
}

fn write_toml_file(content: impl AsRef<str>, path: &Path) -> std::io::Result<()> {
    let mut file = fs::File::create(path)?;
    file.write_all(GENERATED_HEADER_TOML.as_bytes())?;
    file.write_all(content.as_ref().as_bytes())?;
    file.write_all(b"\n")?;
    Ok(())
}

/// Formats the generated token stream into Rust source code using prettyplease.
///
/// prettyplease handles:
/// 1. Formatting macro contents (rustfmt leaves them as-is)
/// 2. Converting `#[doc = "..."]` attributes back to `/// ...` doc comments
/// 3. Converting `#[comment = "..."]` attributes to `// ...` line comments
///    (undocumented feature, but stable - this is how we embed comments in
///    generated code since TokenStream cannot represent comments directly)
fn to_string(tokens: TokenStream) -> String {
    let syntax = syn::parse_file(&tokens.to_string()).unwrap_or_else(|e| {
        panic!("Parse error at {:?}: {}", e.span().start(), e);
    });
    prettyplease::unparse(&syntax)
}
